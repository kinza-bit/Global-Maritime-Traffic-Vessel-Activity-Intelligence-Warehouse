-- 02_dw_schema.sql  (PostgreSQL)  -- project_dw: dimensions + facts
-- Surrogate keys: integer IDENTITY (BY DEFAULT so we can insert the -1 "Unknown"
-- member explicitly). Natural keys are kept with a UNIQUE constraint.

-- ---------------------------------------------------------------- dimensions
CREATE TABLE IF NOT EXISTS project_dw.dim_date (
  sk_date          INTEGER  PRIMARY KEY,          -- smart key YYYYMMDD
  full_date        DATE     NOT NULL UNIQUE,      -- natural key
  day_of_week_num  SMALLINT NOT NULL,             -- 1=Mon .. 7=Sun
  day_of_week      TEXT     NOT NULL,
  day_of_month     SMALLINT NOT NULL,
  month_number     SMALLINT NOT NULL,
  month_name       TEXT     NOT NULL,
  quarter          SMALLINT NOT NULL,
  year             SMALLINT NOT NULL,
  fiscal_year      SMALLINT NOT NULL              -- Jul-Jun, named by end year
);

CREATE TABLE IF NOT EXISTS project_dw.dim_vessel (
  sk_vessel            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vessel_id            TEXT NOT NULL UNIQUE,      -- natural key (GFW vessel id)
  vessel_name          TEXT,
  ssvid                TEXT,                      -- MMSI
  imo                  TEXT,
  callsign             TEXT,
  flag_country         TEXT,
  primary_vessel_type  TEXT,
  length_m             NUMERIC(10,2),
  tonnage_gt           NUMERIC(10,2),
  engine_power_kw      NUMERIC(10,2),
  max_speed_kn         NUMERIC(10,2),
  has_vessel_details   BOOLEAN NOT NULL DEFAULT FALSE,  -- found in stg_vessels?
  dw_load_ts           TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS project_dw.dim_port (
  sk_port         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  port_name       TEXT NOT NULL UNIQUE,           -- natural key (standardised anchorage name)
  anchorage_name  TEXT,
  port_country    TEXT,                           -- ISO3 from anchorage flag
  latitude        NUMERIC(10,6),
  longitude       NUMERIC(10,6),
  coastal_region  TEXT,                           -- not in Silver -> NULL
  dw_load_ts      TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS project_dw.dim_location (
  sk_location      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id      TEXT NOT NULL UNIQUE,          -- natural key e.g. HS1-MPA0-NT0
  eez_name         TEXT,                          -- not in Silver -> NULL
  high_seas_flag   BOOLEAN,
  mpa_name         TEXT,                          -- not in Silver -> NULL
  mpa_flag         BOOLEAN,
  mpa_no_take_flag BOOLEAN,
  dw_load_ts       TIMESTAMP NOT NULL DEFAULT now(),
  UNIQUE (high_seas_flag, mpa_flag, mpa_no_take_flag)
);

-- --------------------------------------------------------------------- facts
-- Grain: one row per completed port visit (one vessel, one anchorage).
CREATE TABLE IF NOT EXISTS project_dw.fact_port_visit (
  fact_port_visit_key  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id             TEXT    NOT NULL UNIQUE,   -- degenerate dimension / natural key
  visit_id             TEXT,
  sk_date              INTEGER NOT NULL REFERENCES project_dw.dim_date(sk_date),
  sk_vessel            INTEGER NOT NULL REFERENCES project_dw.dim_vessel(sk_vessel),
  sk_port              INTEGER NOT NULL REFERENCES project_dw.dim_port(sk_port),
  sk_location          INTEGER NOT NULL REFERENCES project_dw.dim_location(sk_location),
  start_ts             TIMESTAMP NOT NULL,
  end_ts               TIMESTAMP NOT NULL,
  duration_hrs         NUMERIC(10,2),
  confidence           INT,
  end_at_dock          BOOLEAN,
  start_dist_port_km   NUMERIC(10,2),
  end_dist_port_km     NUMERIC(10,2),
  start_dist_shore_km  NUMERIC(10,2),
  end_dist_shore_km    NUMERIC(10,2),
  silver_run_id        TEXT,
  dw_load_ts           TIMESTAMP NOT NULL DEFAULT now()
);

-- Grain: one row per AIS transponder gap for one vessel.
CREATE TABLE IF NOT EXISTS project_dw.fact_ais_gap (
  fact_ais_gap_key     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id             TEXT    NOT NULL UNIQUE,
  sk_date              INTEGER NOT NULL REFERENCES project_dw.dim_date(sk_date),
  sk_vessel            INTEGER NOT NULL REFERENCES project_dw.dim_vessel(sk_vessel),
  sk_location          INTEGER NOT NULL REFERENCES project_dw.dim_location(sk_location),
  start_ts             TIMESTAMP NOT NULL,
  end_ts               TIMESTAMP NOT NULL,
  duration_hours       NUMERIC(10,2),
  distance_km          NUMERIC(10,2),
  implied_speed_knots  NUMERIC(10,2),
  intentional_disabling BOOLEAN,
  off_lat              NUMERIC(10,6),
  off_lon              NUMERIC(10,6),
  on_lat               NUMERIC(10,6),
  on_lon               NUMERIC(10,6),
  positions_per_day_sat_reception NUMERIC(10,2),
  silver_run_id        TEXT,
  dw_load_ts           TIMESTAMP NOT NULL DEFAULT now()
);

-- Grain: one row per detected activity segment (fishing / loitering /
-- encounter) for one vessel. Encounters appear once per vessel (.1 / .2).
CREATE TABLE IF NOT EXISTS project_dw.fact_vessel_event (
  fact_vessel_event_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id              TEXT    NOT NULL UNIQUE,
  event_base_id         TEXT,
  event_type            TEXT    NOT NULL
                        CHECK (event_type IN ('FISHING','LOITERING','ENCOUNTER')),
  sk_date               INTEGER NOT NULL REFERENCES project_dw.dim_date(sk_date),
  sk_vessel             INTEGER NOT NULL REFERENCES project_dw.dim_vessel(sk_vessel),
  sk_encountered_vessel INTEGER REFERENCES project_dw.dim_vessel(sk_vessel), -- encounters only
  sk_location           INTEGER NOT NULL REFERENCES project_dw.dim_location(sk_location),
  start_ts              TIMESTAMP NOT NULL,
  end_ts                TIMESTAMP NOT NULL,
  lat                   NUMERIC(10,6),
  lon                   NUMERIC(10,6),
  duration_hours        NUMERIC(10,2),
  avg_speed_knots       NUMERIC(10,2),
  total_distance_km     NUMERIC(10,2),
  avg_dist_shore_km     NUMERIC(10,2),
  start_dist_shore_km   NUMERIC(10,2),
  end_dist_shore_km     NUMERIC(10,2),
  start_dist_port_km    NUMERIC(10,2),
  end_dist_port_km      NUMERIC(10,2),
  potential_risk        BOOLEAN,
  encounter_type        TEXT,
  encounter_median_speed_knots NUMERIC(10,2),
  encounter_median_distance_km NUMERIC(10,2),
  silver_run_id         TEXT,
  dw_load_ts            TIMESTAMP NOT NULL DEFAULT now()
);

-- Indexes on foreign keys (join speed for reporting)
CREATE INDEX IF NOT EXISTS ix_fpv_vessel   ON project_dw.fact_port_visit(sk_vessel);
CREATE INDEX IF NOT EXISTS ix_fpv_port     ON project_dw.fact_port_visit(sk_port);
CREATE INDEX IF NOT EXISTS ix_fpv_date     ON project_dw.fact_port_visit(sk_date);
CREATE INDEX IF NOT EXISTS ix_fag_vessel   ON project_dw.fact_ais_gap(sk_vessel);
CREATE INDEX IF NOT EXISTS ix_fag_date     ON project_dw.fact_ais_gap(sk_date);
CREATE INDEX IF NOT EXISTS ix_fve_vessel   ON project_dw.fact_vessel_event(sk_vessel);
CREATE INDEX IF NOT EXISTS ix_fve_date     ON project_dw.fact_vessel_event(sk_date);
CREATE INDEX IF NOT EXISTS ix_fve_type     ON project_dw.fact_vessel_event(event_type);

-- Audit table for data quality results (used by 06_dq_checks.sql)
CREATE TABLE IF NOT EXISTS project_audit.dq_results (
  dq_result_id  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  checked_at    TIMESTAMP NOT NULL DEFAULT now(),
  check_id      TEXT NOT NULL,
  dimension     TEXT NOT NULL,     -- Completeness / Accuracy / Integrity / Uniqueness
  description   TEXT NOT NULL,
  table_name    TEXT NOT NULL,
  rows_checked  BIGINT,
  rows_failed   BIGINT,
  severity      TEXT NOT NULL,     -- CRITICAL / WARNING
  status        TEXT NOT NULL      -- PASS / FAIL / WARN
);
